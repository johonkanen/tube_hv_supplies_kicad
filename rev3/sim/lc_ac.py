#!/usr/bin/env python3
"""HV supplies rev 3: the second LC stage (first-pass missed item 6, review M19) and the input
filter, as passive AC networks in ngspice, cross-checked against the Python model hvnet.py.

Questions:
  1. Variant A (first pass: 33 uH / 47 uF at the output) resonates at about 4 kHz. How high is
     the peak in the open-loop output impedance and in the duty-to-output transfer, with a low
     ESR (hot electrolytic, 0.1 ohm) and a typical one (0.5 ohm)?
  2. Variant B (second pass: both 47 uF at the intermediate node, 33 uH || 5.6 ohm, 1 uF film at
     the output): where is the second-stage resonance, how damped, and is the switching ripple
     still attenuated?
  3. Input filter (L101 33 uH between C101 on B_P and the two bridge-local 47 uF on UIN): its
     output impedance against the bridges' negative input resistance (Middlebrook), the PSU
     side modelled as 0.3 ohm + 1 uH of cable.

Run: python3 rev3/sim/lc_ac.py   (writes rev3/sim/lc_ac_results.md)
"""
import os
import subprocess
import tempfile

import numpy as np

import hvnet

HERE = os.path.dirname(os.path.abspath(__file__))


def spice_network(p, r_load, drive):
    """ngspice netlist of hvnet's network. drive = 'sw' (AC 1 V at sw) or 'tab' (AC 1 A into tab,
    sw shorted)."""
    lines = ["* hvnet " + p["variant"],
             ("VSW sw 0 DC 0 AC 1" if drive == "sw" else "VSW sw 0 DC 0"),
             f"RL1 sw n1 {p['RL1']}", f"L1 n1 uc {p['L1']}"]
    for i in range(p["n_uc"]):
        lines += [f"RC{i} uc c{i} {p['ESR']}", f"CU{i} c{i} ic {p['Cel']}"]
    lines += ["VIC ic 0 DC 0"]                                    # ammeter: i_C into the electrolytics
    lines += [f"RL2 uc n2 {p['RL2']}", f"L2 n2 vo {p['L2']}"]
    if p["Rd"]:
        lines += [f"RD uc vo {p['Rd']}"]
    for i, (c, r) in enumerate(p["Cvo"]):
        r = p["ESR"] if r == "ESR" else r
        lines += [f"RV{i} vo v{i} {r}", f"CV{i} v{i} 0 {c}"]
    lines += [f"RS vo tab {p['Rs']}"]
    if r_load:
        lines += [f"RLD tab 0 {r_load}"]
    else:
        lines += ["RLD tab 0 1G"]
    if drive == "tab":
        lines += ["IINJ 0 tab DC 0 AC 1"]
    lines += [".ac dec 200 10 300k", ".control", "run",
              "wrdata {out} v(tab) i(VIC)", "quit", ".endc", ".end"]
    return lines


def run_spice(lines):
    with tempfile.TemporaryDirectory() as d:
        out = os.path.join(d, "o.txt")
        cir = os.path.join(d, "c.cir")
        with open(cir, "w") as f:
            f.write("\n".join(lines).replace("{out}", out) + "\n")
        r = subprocess.run(["ngspice", "-b", cir], capture_output=True, text=True)
        if not os.path.exists(out):
            raise SystemExit(r.stdout[-2000:] + r.stderr[-2000:])
        a = np.loadtxt(out)
    # wrdata complex: f re im f re im
    f = a[:, 0]
    v = a[:, 1] + 1j * a[:, 2]
    i = a[:, 4] + 1j * a[:, 5]
    return f, v, i


def peak(f, mag, lo, hi):
    m = (f >= lo) & (f <= hi)
    k = np.argmax(mag[m])
    return f[m][k], mag[m][k]


def input_filter(esr):
    """|Z| seen by the bridges at UIN: C101 47 uF on B_P (behind 0.3 ohm + 1 uH to the PSU),
    L101 33 uH (DCR 0.05), 2 x 47 uF bridge-local caps on UIN (each behind its fuse, ~0.1 ohm)."""
    f = np.logspace(1, 5.5, 2000)
    s = 2j * np.pi * f
    z_psu = 0.3 + s * 1e-6
    z_c101 = esr + 1 / (s * 47e-6)
    z_bp = 1 / (1 / z_psu + 1 / z_c101)
    z_l = 0.05 + s * 33e-6
    z_cu = (esr + 0.1 + 1 / (s * 47e-6)) / 2
    z = 1 / (1 / (z_bp + z_l) + 1 / z_cu)
    return f, np.abs(z)


def main():
    rows = []
    worst_dev = 0.0
    f_chk = None
    for var in ("A", "B", "C"):
        for esr in (0.1, 0.5):
            p = hvnet.params(var, ESR=esr)
            f, v_sw, _ = run_spice(spice_network(p, 700.0, "sw"))
            f2, z_tab, _ = run_spice(spice_network(p, 700.0, "tab"))
            py = hvnet.network(p, f, 700.0)
            dev = max(np.max(np.abs(py["Gvd"] - v_sw) / np.abs(v_sw)),
                      np.max(np.abs(py["Zo"] - z_tab) / np.abs(z_tab)))
            worst_dev = max(worst_dev, dev)
            f_lc1, g1 = peak(f, np.abs(v_sw), 100, 1000)
            fz1, z1 = peak(f2, np.abs(z_tab), 100, 1000)
            fz2, z2 = peak(f2, np.abs(z_tab), 1500, 100e3)
            hvu = hvnet.network(p, [50e3, 100e3], 700.0)["Hvu"]
            rows.append((var, esr, f_lc1, 20 * np.log10(g1), fz1, z1, fz2, z2,
                         abs(hvu[0]), abs(hvu[1])))
            print(var, esr, rows[-1][2:])
    fin = []
    for esr in (0.1, 0.5):
        f, z = input_filter(esr)
        fp, zp = peak(f, z, 300, 30e3)
        fin.append((esr, fp, zp))
    r_neg = 430.0 ** 2 / 300.0
    with open(os.path.join(HERE, "lc_ac_results.md"), "w") as fo:
        fo.write("# Second LC stage and input filter (generated by lc_ac.py)\n\n")
        fo.write("Bridge output network, load 700 ohm (400 V / 0.57 A). Gvd = V_tab / V_sw (duty to output), "
                 "Zo = open-loop output impedance at the tab (no control). Peaks searched in 100-1000 Hz "
                 "(main LC: 3 mH with the electrolytics) and 1.5-100 kHz (second stage; in Gvd it shows no separate peak, it is "
                 "buried under the main LC's roll-off, so it is read in Zo). Hvu = second-stage "
                 "ripple attenuation V_tab / V_uc at 50 / 100 kHz.\n\n")
        fo.write("| Variant | ESR per electrolytic (ohm) | main LC peak: f (Hz), Gvd (dB) | "
                 "Zo peak low: f (Hz), ohm | Zo peak high (2nd stage): f (Hz), ohm | Hvu 50 kHz | Hvu 100 kHz |\n|---|---|---|---|---|---|---|\n")
        for r in rows:
            fo.write(f"| {r[0]} | {r[1]} | {r[2]:.0f}, {r[3]:+.1f} | {r[4]:.0f}, {r[5]:.1f} | "
                     f"{r[6]:.0f}, {r[7]:.2f} | {r[8]:.3f} | {r[9]:.3f} |\n")
        fo.write(f"\nPython model hvnet.py against ngspice: worst relative deviation {worst_dev:.2e} over 10 Hz-300 kHz.\n\n")
        fo.write("Input filter (L101 33 uH, C101 47 uF on B_P, 2 x 47 uF on UIN; PSU 0.3 ohm + 1 uH): output impedance "
                 f"peak seen by the bridges, against the bridges' negative input resistance V^2 / P = {r_neg:.0f} ohm "
                 "at 300 W (Middlebrook: the peak must stay far below it).\n\n| ESR (ohm) | peak f (Hz) | peak |Z| (ohm) |\n|---|---|---|\n")
        for esr, fp, zp in fin:
            fo.write(f"| {esr} | {fp:.0f} | {zp:.2f} |\n")


if __name__ == "__main__":
    main()
