#!/usr/bin/env python3
"""HV supplies rev 3: dedicated fast ADCs for the loop (TI ADS7056, 14 bit, 2.5 MSPS; study 2026-11-24).

The loop channels get one ADS7056 each, all sampled on one shared CS falling edge timed by the PWM
generator (in TCM: the middle of the bridge's high-side conduction; fixed frequency: the period's centre,
where the inductor and capacitor ripple cross their average). Delay model (est.): conversion and read-out
18-20 SCLK at 30 MHz = 0.7 us, isolators about 15 ns each way, FPGA arithmetic about 0.5 us, then the PWM:
in TCM the new duty and frequency apply from the next period (Ts = T_sw, Td from the sample to the middle
of the next period's effect: about 0.75 T_sw + 1.5 us); fixed frequency with a double update per period
(sample at the centre and at the edge: Ts = T_sw / 2, Td about T_sw / 4 + 1.5 us).

1. Margins and output impedance with r3's corners and grid search (PM >= 45 deg, GM >= 8 dB, lowest
   |Zout| 20 Hz-20 kHz) for: today's link, r3's synchronous AD7689 schedule, TCM with the ADS7056 at
   the lowest (40 kHz) and highest (150 kHz) frequency, and the fixed-frequency alternative (470 uH,
   100 kHz).
2. How far the first resonance can move up (the first capacitor shrink) with the ADS7056 schedules:
   C1's electrolytic and the damping leg scaled together.

Run: python3 rev3/sim/r6_sampling.py   (writes r6_results.md; about a minute)
"""
import os

import numpy as np

import filt
import r3_damping as r3

HERE = os.path.dirname(os.path.abspath(__file__))
SCHED = [("today: AD7689 round robin (Ts 32 us, Td 60 us)", 32e-6, 60e-6, 220e-6),
         ("r3 synchronous AD7689 (Ts 20 us, Td 30 us)", 20e-6, 30e-6, 220e-6),
         ("TCM + ADS7056 at 40 kHz (Ts 25 us, Td 20 us)", 25e-6, 20e-6, 220e-6),
         ("TCM + ADS7056 at 150 kHz (Ts 6.7 us, Td 6.5 us)", 6.7e-6, 6.5e-6, 220e-6),
         ("fixed 100 kHz + ADS7056, double update (Ts 5 us, Td 4 us), L1 470 uH", 5e-6, 4e-6, 470e-6)]


def base_for(L1, kc=1.0):
    def b(kw):
        p = r3.chain(1, **kw)
        p = dict(p, L1=L1 * kw.get("kL1", 1.0))
        p["C1"] = [(p["C1"][0][0] * kc, p["C1"][0][1], p["C1"][0][2])] + p["C1"][1:]
        p["C2"] = [p["C2"][0], (p["C2"][1][0] * max(kc, 0.2), p["C2"][1][1], p["C2"][1][2])]
        return p
    return b


def main():
    cs = r3.corners(1)
    L = ["# Sampling for the loop: dedicated fast ADCs (generated by r6_sampling.py)", "", __doc__.split("\n\n")[1].strip(), "",
         "## 1. Margins and output impedance (V_ANODE, recommended filter, r3's 32 tolerance corners)", "",
         "| Schedule | first resonance (Hz) | gains Kp / Ki / Kc | crossover (Hz) | worst PM / GM | max |Zout| 20 Hz-20 kHz (ohm) at f |",
         "|---|---|---|---|---|---|"]
    for name, ts, td, L1 in SCHED:
        b = base_for(L1)
        f1 = filt.resonances(b(dict(kL1=1.0, kC1=1.0, rd=1.5)), 0.3)[0][0]
        best = r3.tune(ts, td, cs, 1, b)
        if best is None:
            L.append(f"| {name} | {f1:.0f} | none | — | — | — |")
            continue
        g, w = best
        L.append(f"| {name} | {f1:.0f} | {g['Kp']} / {g['Ki']} / {g['Kc']} | {w['fc']:.0f} | {w['pm']:.0f} / {w['gm']:.1f} | {w['z']:.2f} at {w['zf']:.0f} |")
    L += ["", "## 2. Smaller first capacitor (electrolytic and damping leg scaled together; ADS7056 schedules)", "",
          "| C1 electrolytic (uF) | f1 (Hz) | TCM 40 kHz (Ts 25, Td 20 us) | TCM 150 kHz (Ts 6.7, Td 6.5 us) | fixed 100 kHz, 470 uH (Ts 5, Td 4 us) |",
          "|---|---|---|---|---|"]
    sub = [c for c in cs if c[0]["rd"] == 1.1]
    for kc in (1.0, 0.68, 0.47, 0.33, 0.22):
        f1 = filt.resonances(base_for(220e-6, kc)(dict(kL1=1.0, kC1=1.0, rd=1.5)), 0.3)[0][0]
        cells = []
        for name, ts, td, L1 in SCHED[2:]:
            best = r3.tune(ts, td, sub, 1, base_for(L1, kc))
            cells.append("none" if best is None else f"PM {best[1]['pm']:.0f} / GM {best[1]['gm']:.1f}, |Z| {best[1]['z']:.1f}")
        L.append(f"| {100 * kc:.0f} | {f1:.0f} | " + " | ".join(cells) + " |")
    L += ["", "Reading: with the sample-to-PWM delay down to one switching period or less, the capacitor-current damping "
          "has phase to spare at the first resonance; the output impedance is then set by the passive network above the "
          "loop's crossover (the second stage's 3.5 ohm peak near 5 kHz and R205), not by the loop."]
    open(os.path.join(HERE, "r6_results.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
