#!/usr/bin/env python3
"""HV supplies rev 3, fifth pass (2026-11-25): one ADS7056 behind an 8:1 multiplexer, no comparators, no latch.

1. Sampling budget: slot = 18 SCLK + CS high (>= 95 ns acquisition, taken 100 ns): 0.70 us at 30 MHz (returned
   clock, pad 16), 1.90 us at 10 MHz (plain); 8 slots per sweep (V_ANODE, I_C14, I_Q12, RAW, V_SCREEN, I_C24, I_Q22,
   bias). The counter steps on the CS falling edge (the sample instant): the driver settles during the frame.
2. Loop margins (r3 model, r6 method) with the per-channel sample interval and the added delay of the sweep
   (the V and I_C samples of one bridge are one slot apart, not simultaneous; the worst sample sits two slots after
   its ideal instant): Td = r6's TCM delay + 2 slots.
3. Output short with the protection through the link and firmware: detection = one sweep (the faulted channel
   has just been sampled) + one slot (conversion and read-out) + 0.3 us (isolator, FPGA, PWM low, driver);
   r7's short model with that trip time; the heartbeat one-shot (about 20 us) as the backstop.
4. TCM valley (zero-voltage turn-on) without synchronous current samples: the turn-on instants come from the TCM law
   (V_raw, V_out, the load current, L); the load current from the I_Q sample at a known offset from the period's
   middle, corrected by the slope V_out / L: error = L tolerance x slope x offset.

Run: python3 rev3/sim/r8_fifth_pass.py   (writes r8_results.md; a few minutes)
"""
import os

import r3_damping as r3
import r6_sampling as r6
import r7_fourth_pass as r7
import tcm

HERE = os.path.dirname(os.path.abspath(__file__))
SLOT = {"30 MHz (returned clock)": 18 / 30e6 + 0.1e-6, "10 MHz (plain)": 18 / 10e6 + 0.1e-6}


def main():
    L = ["# Fifth pass: one multiplexed ADS7056 (generated by r8_fifth_pass.py)", "", __doc__.split("\n\n")[1].strip(), ""]
    L += ["## 1. Sampling budget", "", "| SCLK | slot (us) | sweep of 8 (us) | per channel (kS/s) | samples of each loop channel per TCM period at 150 / 40 kHz | skew V to I_C / V to I_Q of one bridge (us) |",
          "|---|---|---|---|---|---|"]
    for k, s in SLOT.items():
        sw = 8 * s
        L.append(f"| {k} | {s * 1e6:.2f} | {sw * 1e6:.1f} | {1e-3 / sw:.0f} | {(1 / 150e3) / sw:.2f} / {(1 / 40e3) / sw:.1f} | {s * 1e6:.2f} / {2 * s * 1e6:.2f} |")
    L += ["", "The driver (OPA2836, unity) and the 33 ohm / 680 pF bucket settle within about 0.25 us to 14 bits; the frame gives "
          "0.6 us (30 MHz) after each channel change: settled. Channel-to-channel crosstalk through the multiplexer's charge: "
          "below 1 LSB after the frame.", ""]
    cs = r3.corners(1)
    L += ["## 2. Loop margins (V_ANODE, r3's 32 corners)", "", "| Case | Ts / Td (us) | gains Kp / Ki / Kc | worst PM / GM | max |Zout| 20 Hz-20 kHz (ohm) |", "|---|---|---|---|---|"]
    s30, s10 = SLOT["30 MHz (returned clock)"], SLOT["10 MHz (plain)"]
    cases = [("fourth pass: six ADS7056, 150 kHz", 6.7e-6, 6.5e-6), ("fourth pass: six ADS7056, 40 kHz", 25e-6, 20e-6),
             ("mux at 30 MHz, 150 kHz (one sweep per period)", 6.7e-6, 6.5e-6 + 2 * s30),
             ("mux at 30 MHz, 40 kHz", 25e-6, 20e-6 + 2 * s30),
             ("mux at 10 MHz plain: a sweep every 15.2 us", 8 * s10, 8 * s10 + 2 * s10 + 1.5e-6)]
    for name, ts, td in cases:
        best = r3.tune(ts, td, cs, 1, r6.base_for(220e-6))
        if best is None:
            L.append(f"| {name} | {ts * 1e6:.1f} / {td * 1e6:.1f} | none | — | — |")
            continue
        g, w = best
        L.append(f"| {name} | {ts * 1e6:.1f} / {td * 1e6:.1f} | {g['Kp']} / {g['Ki']} / {g['Kc']} | {w['pm']:.0f} / {w['gm']:.1f} | {w['z']:.2f} at {w['zf']:.0f} Hz |")
    L += ["", "## 3. Output short through the link (r7 model, 50 mohm at the V_ANODE tab)", "",
          "| Protection | trip after (us) | L1 peak (A) / B (T) | R205 energy (J) | I_C shunt (A) |", "|---|---|---|---|---|"]
    trips = [("comparator (fourth pass)", 1.0e-6), ("firmware, mux at 30 MHz", 8 * s30 + s30 + 0.3e-6),
             ("firmware, mux at 10 MHz", 8 * s10 + s10 + 0.3e-6), ("heartbeat one-shot only (firmware hung)", 20e-6)]
    for name, t in trips:
        r = r7.short_case(name, 220e-6, 50, 1.0, "short", 1e-6 + t)
        L.append(f"| {name} | {t * 1e6:.1f} | {r['il_pk']:.1f} / {r['bpk']:.2f} | {r['e_rs']:.2f} | {r['ic_pk']:.0f} |")
    rs = r7.short_case("screen", 470e-6, 64, 2.2, "short", 1e-6 + 8 * s30 + s30 + 0.3e-6, True)
    L.append(f"| V_SCREEN short, firmware, 30 MHz | {(8 * s30 + s30 + 0.3e-6) * 1e6:.1f} | {rs['il_pk']:.1f} / {rs['bpk']:.2f} | {rs['e_rs']:.2f} (R212) | {rs['ic_pk']:.0f} |")
    L += ["", "## 4. TCM valley without synchronous current samples", "",
          "| Operating point | f (kHz) | valley target (A) | I_Q sample offset (us) | slope (A/us) | load-current error at L +-10 % (A) |", "|---|---|---|---|---|---|"]
    d = tcm.DESIGN
    for vo, io in ((400, 0.7), (300, 0.5), (200, 0.35), (100, 0.1)):
        f = tcm.law(vo, io, 420.0, d)
        sl = vo / d["L"] / 1e6
        off = 2 * s30
        L.append(f"| {vo} V / {io} A | {f / 1e3:.0f} | -{d['izvs']:.2f} | {off * 1e6:.1f} | {sl:.2f} | {0.1 * sl * off * 1e6:.2f} |")
    L += ["", f"izvs (valley needed to swing the node in 600 ns with 220 pF): {d['izvs']:.2f} A."]
    open(os.path.join(HERE, "r8_results.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
