#!/usr/bin/env python3
"""HV supplies rev 3: how fast V_ANODE and V_SCREEN fall after HV_PERMIT drops, with the tubes
as the only load (review K12 / U14, the power amp's M28; interfaces.md 8: BIAS_OK drops 22-117 ms
after a lost -80 V, the bias at most 1.7 V hot by then).

After the inhibit both bridges stop switching within 100 us (opto + filter + logic + UCC21520
DIS); nothing more is taken from the raw rail. What is left is the energy in the output
capacitors (100 uF electrolytic + 1 uF film per output, 8.1 J at 400 V) and it can only go into
the tubes, the bleeders (2 x 110 kohm per output), the measurement dividers (3.015 Mohm) and the
V_ANODE LED string (1 Mohm). D201 (anode V_SCREEN, cathode V_ANODE) keeps V_SCREEN at most
0.7 V above V_ANODE, so the screen capacitor follows the anode down.

Tube model (four output tubes together, crude but monotonic): cathode current
  I_k = I0 * (V_screen / 390 V)^1.5, split 88 % anode / 12 % screen while V_anode > 50 V
(the screen controls a pentode's cathode current; below the knee the screen takes more, which
only makes the screen fall faster). I0 is the total cathode current at the nominal voltages:
  cold (cut off by the bias clamp): 0; idle: 0.2 A (4 x 50 mA); a 'hot' idle: 0.4 A;
  grid at 0 V (bias lost entirely, the K12 worst case): 2.0 A.

Run: python3 rev3/sim/discharge.py   (writes rev3/sim/discharge_results.md)
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
C = 101e-6
R_A = 1 / (1 / 220e3 + 1 / 3.015e6 + 1 / 1e6)
R_S = 1 / (1 / 220e3 + 1 / 3.015e6)


def run(i0, va0=400.0, vs0=390.0, t_end=120.0):
    dt, t = 1e-5, 0.0
    va, vs = va0, vs0
    e_tube = 0.0
    hit = {}
    p_peak = 0.0
    while t < t_end:
        ik = i0 * max(vs, 0) ** 1.5 / 390.0 ** 1.5
        ia, isg = 0.88 * ik, 0.12 * ik
        ib_a, ib_s = va / R_A, vs / R_S
        dva = -(ia + ib_a) / C
        dvs = -(isg + ib_s) / C
        if vs > va + 0.7:                       # D201 conducts: the two capacitors move together
            dva = dvs = -(ia + isg + ib_a + ib_s) / (2 * C)
        p = ia * va + isg * vs
        p_peak = max(p_peak, p)
        e_tube += p * dt
        va += dva * dt
        vs += dvs * dt
        t += dt
        for lvl in (200.0, 100.0, 50.0):
            if lvl not in hit and max(va, vs) < lvl:
                hit[lvl] = t
        if max(va, vs) < 40.0:
            break
        if t > 1.0:
            dt = 1e-3
    return hit, e_tube, p_peak


def main():
    rows = []
    for name, i0 in (("cold (bias clamped, tubes cut off): bleeders only", 0.0), ("idle, 4 x 50 mA", 0.2),
                     ("hot idle, 4 x 100 mA", 0.4), ("grid at 0 V (bias lost), about 4 x 0.5 A", 2.0)):
        hit, e, pk = run(i0)
        rows.append((name, hit, e, pk))
        print(name, hit, e, pk)
    e_cap = 0.5 * C * (400 ** 2 + 390 ** 2)
    with open(os.path.join(HERE, "discharge_results.md"), "w") as f:
        f.write("# Output fall after HV_PERMIT drops (generated by discharge.py)\n\n")
        f.write(f"Start: V_ANODE 400 V, V_SCREEN 390 V, {C * 1e6:.0f} uF each, {e_cap:.1f} J stored in both. "
                f"Bleeder paths: V_ANODE {R_A / 1e3:.0f} kohm, V_SCREEN {R_S / 1e3:.0f} kohm.\n\n")
        f.write("| Tube load after the inhibit | time to below 200 V | below 100 V | below 50 V | energy into the tubes (J) | peak tube dissipation, all four (W) |\n|---|---|---|---|---|---|\n")
        fmt = lambda x: "-" if x is None else (f"{x * 1e3:.0f} ms" if x < 1 else f"{x:.1f} s")
        for name, hit, e, pk in rows:
            f.write(f"| {name} | {fmt(hit.get(200.0))} | {fmt(hit.get(100.0))} | {fmt(hit.get(50.0))} | {e:.1f} | {pk:.0f} |\n")


if __name__ == "__main__":
    main()
