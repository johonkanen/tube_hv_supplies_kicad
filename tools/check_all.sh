#!/usr/bin/env bash
# Run every verification step. Exit status is non-zero if any step fails.
# Each phase adds its steps here (playbook principle 5, PLAN.md section 6).
# The tools are the proteus2kicad submodule in tools/p2k; board values in p2k_config.py.
# Generation stopped (STATUS.md "Decisions", D-STOP): kicad/ and lib/ are hand-edited, so no step
# regenerates or byte-compares them (make_part_map / gen_symbols / gen_footprints --check and
# make_pcb --check are gone; the generators are frozen in tools/generate/). Every step below checks the
# committed files against the Proteus sources or the KiCad rules. ipc356 --check stays: reference/ is
# the Proteus side of every comparison (parsed from source/, never edited by hand).
set -u
cd "$(dirname "$0")/.."
[ -x tools/p2k/bin/p2k ] || { echo "tools/p2k missing: git submodule update --init"; exit 1; }
fail=0
mkdir -p build/tmp
log=build/tmp/check_all.log; : > "$log"
step() {
    echo "== $1" | tee -a "$log"; shift
    "$@" 2>&1 | tee -a "$log"
    [ "${PIPESTATUS[0]}" -eq 0 ] || { echo "!! FAILED: $*" | tee -a "$log"; fail=1; }
}

# Phase 0: environment and sources
step "KiCad environment" tools/p2k/bin/kipy -c "import pcbnew; v = pcbnew.GetBuildVersion(); print('pcbnew', v); assert v.startswith('10.0.7'), v"
step "IPC-D-356A parser self-check" tools/p2k/bin/p2k ipc356 --check
step "Gerber X2 export vs IPC (pads, vias, drills, outline)" tools/p2k/bin/p2k check_sources
# Phase 1: schematic
step "Symbol pin sets vs IPC" tools/p2k/bin/p2k check_symbols
step "ERC" tools/p2k/bin/p2k erc
# all 6 sheets drawn: every part must be present (no --allow-missing)
step "Netlist comparison vs IPC" tools/p2k/bin/p2k compare_netlists
# strict net_names (on by default, p2k D-Z): a KiCad net that is an IPC net under another name fails,
# so a missing / typo'd NET_ALIASES entry (+1V0_BIAS, the finding 7 current nets) fails here
# Phase 2: footprints
step "Footprints vs IPC pad geometry (fit and pcbnew placement)" tools/p2k/bin/kipy -m p2k.check_footprints --pcbnew
step "Pin order vs unmoved KiCad base footprints" tools/p2k/bin/p2k check_pin_order
# Phase 3: PCB (hand-edited since D-STOP; generated by tools/generate/make_pcb.sh until then)
step "Board pads, holes, vias vs IPC (position, size, nets 1:1)" tools/p2k/bin/kipy -m p2k.check_board
step "Board copper connectivity after zone fill" tools/p2k/bin/kipy -m p2k.assign_nets --check
step "DRC with schematic parity" tools/p2k/bin/p2k drc
# Phase 4: the finished board against the Proteus CADCAM files (independent of the generators)
step "IPC-D-356 from the board vs Proteus (pads, vias, holes, nets)" tools/p2k/bin/p2k ipc356_diff
step "Gerber round trip vs Proteus (copper XOR, coverage, drills)" tools/p2k/bin/p2k gerber_roundtrip --check
# Phase 5: the pad decisions (round trip and ipc356_diff accept other pad shapes / larger drills)
# pad sizes: KiCad pads except the PROTEUS_PADS_CHECK parts (user decisions A2 and Phase 5: + J2,
# + Q3 Q4 Q7 Q8 with the gerber TO-220 pad, J1 round except the square J1-1)
# J1-1 is square since the J1 renumbering (user decision 2026-11-20: "square pin-1 pad on the real pin 1";
# the Proteus flash is round). p2k.check_pads has no per-pad exception key (p2k candidate 30), so this
# step accepts exactly the four J1-1 lines (square 0.762 pad vs the round 0.762 flash, one per copper
# layer) and nothing else; a round J1-1 again (stale exception) or any other pad error fails.
check_pads_j1() {
    local out want got
    out=$(tools/p2k/bin/kipy -m p2k.check_pads 2>&1); echo "$out"
    want=$(for l in F.Cu In1.Cu In2.Cu B.Cu; do
        echo "check_pads: J1-1 $l: board pad 0.762 x 0.762 mm, 0.581 mm^2; Proteus flash (C) 0.762 x 0.762 mm, 0.456 mm^2"; done)
    got=$(echo "$out" | grep "^check_pads: " | grep -v " pad layers compared ")
    echo "$out" | grep -q " pad layers compared with the Proteus flashes and drills: FAILED (4)$" && [ "$got" = "$want" ] \
        || { echo "check_pads: expected exactly the 4 accepted J1-1 lines (square pin-1 pad)"; return 1; }
    echo "check_pads: OK except the accepted square J1-1 (user decision 2026-11-20, 4 pad layers)"
}
step "Proteus-pad parts: board pads = Proteus flashes and drills (J1-1 square: accepted)" check_pads_j1

echo
pending=$(grep -c "PENDING USER DECISION" "$log")
if [ $fail -ne 0 ]; then echo "SOME CHECKS FAILED"
elif [ "$pending" -ne 0 ]; then echo "ALL CHECKS PASSED, EXCEPT $pending PENDING USER DECISION(S):"; grep "PENDING USER DECISION" "$log" | sed 's/^/  /'
else echo "ALL CHECKS PASSED"; fi
exit $fail
